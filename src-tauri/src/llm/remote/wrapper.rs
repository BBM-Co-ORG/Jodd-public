    #[test]
    fn the_watchdog_kills_a_hung_cli_and_cleans_up() {
        let fx = fixture(false, Some(2));
        let started = std::time::Instant::now();
        let pidfile = fx.dir.path().join("fake.pid");
        let (code, _, err) = run(&fx, &req("run", "codex"),
            &[("FAKE_SLEEP", "40"), ("FAKE_PIDFILE", &pidfile.to_string_lossy())], &v2("-", "x"));
        assert_eq!(code, 124, "{err}");
        assert!(err.contains("timed out after 2s"), "{err}");
        assert!(started.elapsed() < std::time::Duration::from_secs(15));
        assert_eq!(leftover_scratch(&fx), 0);
        // The fake's own `sleep` must be gone, not orphaned.
        assert!(fake_is_gone(&pidfile), "the CLI must be killed too");
    }

    #[test]
    fn a_client_that_stops_reading_leaves_no_scratch_behind() {
        // The wrapper's stdout/stderr readers vanish while the CLI is still
        // running but its stdin stays open, so only the watchdog ends the run
        // and the replay and the "timed out" line hit a closed pipe (SIGPIPE).
        let fx = fixture(false, Some(2));
        let pidfile = fx.dir.path().join("fake.pid");
        let mut child = spawn(&fx, &req("run", "codex"), &[("FAKE_SLEEP", "40"), ("FAKE_PIDFILE", &pidfile.to_string_lossy())]);
        let mut sin = child.stdin.take().unwrap();
        sin.write_all(&v2("-", "secret prompt")).unwrap();
        drop(child.stdout.take());
        drop(child.stderr.take());
        let started = std::time::Instant::now();
        let (code, _, err) = finish(child);
        drop(sin);
        assert_ne!(code, -2, "{err}");
        assert!(started.elapsed() < std::time::Duration::from_secs(15));
        assert_eq!(leftover_scratch(&fx), 0, "the prompt must not outlive the call");
        assert!(fake_is_gone(&pidfile), "the CLI must be killed too");
    }
